// Copies the privacy notice and terms (docs/legal/*.md) into the app as app/src/content/legal.ts,
// so parents can read them before agreeing at sign-up. Run after editing either document:
//   node scripts/build-legal.mjs
// server/test/legal-sync.test.ts fails if the app copy is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
/** A template literal keeps the text readable (and diffable) in the generated file. */
const literal = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

export function buildLegalModule() {
  const privacy = read("docs/legal/PRIVACY_NOTICE.md");
  const terms = read("docs/legal/TERMS.md");
  const version = privacy.match(/^Version (\S+)/m)?.[1];
  if (!version || terms.match(/^Version (\S+)/m)?.[1] !== version) {
    throw new Error("PRIVACY_NOTICE.md and TERMS.md must both start with the same 'Version …' line.");
  }
  return [
    "// Generated by scripts/build-legal.mjs from docs/legal/*.md. Edit those files, then run",
    "//   node scripts/build-legal.mjs",
    "// When the texts change for real, also bump CONSENT_VERSION in server/src/app.ts to match LEGAL_VERSION.",
    "",
    `export const LEGAL_VERSION = ${JSON.stringify(version)};`,
    "",
    `export const PRIVACY_NOTICE = ${literal(privacy)};`,
    "",
    `export const TERMS = ${literal(terms)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "app/src/content/legal.ts"), buildLegalModule());
  console.log("Wrote app/src/content/legal.ts");
}
