// Writes app/src/local/content-files.generated.ts: the content the phone app needs for standalone mode (task T8b), as one import
// per JSON file under content/. Metro bundles the JSON itself, so content/ stays the only copy; this index only changes when a
// content file is added, removed or renamed. Run after adding content (CI fails if it is stale):
//   node scripts/bundle-content.mjs
//
// Included: what loadContent() and Hoot's helplines read. Left out: hoot-redteam.json (test prompts, not for children) and
// facts/keywords.json (used only by scripts/check-fact-sources.mjs).
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = join(root, "content");
const out = join(root, "app/src/local/content-files.generated.ts");

const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : n.endsWith(".json") ? [join(d, n)] : []));
const rel = (f) => relative(contentDir, f).replace(/\\/g, "/");
const needed = (r) =>
  ["knowledge-map.json", "resources.json", "helplines.json"].includes(r) || /^(lessons|puzzles|spelling|chess)\//.test(r) || /^facts\/b[1-5]\.json$/.test(r);

const files = walk(contentDir).map(rel).filter(needed).sort();
const lines = [
  "// Generated by scripts/bundle-content.mjs. Do not edit: run `node scripts/bundle-content.mjs` after adding, removing or renaming",
  "// a file in content/. The content the phone app bundles for standalone mode (docs/STANDALONE.md), keyed by its path under content/.",
  ...files.map((f, i) => `import f${i} from "../../../content/${f}";`),
  "",
  "export const contentFiles: Readonly<Record<string, unknown>> = {",
  ...files.map((f, i) => `  ${JSON.stringify(f)}: f${i},`),
  "};",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${relative(root, out).replace(/\\/g, "/")}: ${files.length} content files.`);
