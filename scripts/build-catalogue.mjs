// Writes the content catalogue (all lessons, puzzles and resources) into README.md
// between the CATALOGUE markers. Run after adding or changing content:
//   node scripts/build-catalogue.mjs

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : n.endsWith(".json") ? [join(d, n)] : []));

const map = read("content/knowledge-map.json");
const lessons = walk(join(root, "content/lessons")).map((f) => JSON.parse(readFileSync(f, "utf8")));
const puzzles = walk(join(root, "content/puzzles")).map((f) => JSON.parse(readFileSync(f, "utf8")));
const resources = read("content/resources.json").resources;
const lock = { religion: "🔒 religion", body: "🔒 body", politics: "🔒 politics" };

const L = [];
const reviewed = lessons.filter((l) => l.status === "reviewed").length;
const questions = lessons.reduce((n, l) => n + l.quiz.length, 0);
const covered = new Set(lessons.flatMap((l) => l.outcomes)).size;
const totalOutcomes = map.cells.reduce((n, c) => n + c.outcomes.length, 0);

L.push(`**${lessons.length} lessons** (${reviewed} reviewed, ${lessons.length - reviewed} draft) · **${questions} quiz questions** · **${puzzles.reduce((n, p) => n + p.puzzles.length, 0)} brain puzzles** · **${resources.length} free resources** · **${covered}/${totalOutcomes} outcomes covered**`, "");
L.push("🔒 = sensitive topic, hidden until a parent unlocks it with their PIN. Everything is a **draft** until two reviewers approve it (see [`docs/NEEDS_APPROVAL.md`](docs/NEEDS_APPROVAL.md)).", "");

// summary table
const subjects = map.subjects;
L.push(`| Age group | ${subjects.map((s) => s.name).join(" | ")} | Total |`);
L.push(`|---|${subjects.map(() => "---").join("|")}|---|`);
for (const b of map.bands) {
  const row = subjects.map((s) => {
    const n = lessons.filter((l) => l.band === b.id && l.subject === s.id).length;
    return s.bands && !s.bands.includes(b.id) ? "—" : String(n);
  });
  L.push(`| ${b.name} (${b.ages[0]}–${b.ages[1]}) | ${row.join(" | ")} | ${lessons.filter((l) => l.band === b.id).length} |`);
}
L.push("");

for (const b of map.bands) {
  const bl = lessons.filter((l) => l.band === b.id);
  L.push(`<details><summary><b>${b.name} (ages ${b.ages[0]}–${b.ages[1]})</b>: ${bl.length} lessons</summary>`, "");
  for (const s of subjects) {
    const sl = bl.filter((l) => l.subject === s.id).sort((x, y) => x.title.localeCompare(y.title));
    if (!sl.length) continue;
    L.push(`- **${s.name}:** ${sl.map((l) => `${l.title}${l.sensitive ? ` (${lock[l.sensitive]})` : ""}`).join(" · ")}`);
  }
  const ps = puzzles.find((p) => p.band === b.id);
  if (ps) L.push(`- **🧩 ${ps.title}:** ${ps.puzzles.length} puzzles (${[...new Set(ps.puzzles.map((p) => p.type))].join(", ")})`);
  L.push("", "</details>", "");
}

L.push("<details><summary><b>Free resources we point to</b></summary>", "");
for (const r of [...resources].sort((a, b) => a.name.localeCompare(b.name))) {
  L.push(`- [${r.name}](${r.url}): ${r.description} *(ages: ${r.bands.map((x) => map.bands.find((b) => b.id === x).ages.join("–")).join(", ")})*`);
}
L.push("", "</details>");

const readmePath = join(root, "README.md");
const readme = readFileSync(readmePath, "utf8");
const start = "<!-- CATALOGUE:START (generated by scripts/build-catalogue.mjs) -->";
const end = "<!-- CATALOGUE:END -->";
const block = `${start}\n${L.join("\n")}\n${end}`;
const next = readme.includes(start)
  ? readme.replace(new RegExp(`${start.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${end}`), block)
  : readme.replace("## Repository layout", `## What's inside\n\n${block}\n\n## Repository layout`);
writeFileSync(readmePath, next);
console.log(`README catalogue updated: ${lessons.length} lessons, ${resources.length} resources.`);
